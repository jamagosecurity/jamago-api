using System.Globalization;
using Jama.Application.Common.Interfaces;

namespace Jama.Infrastructure.Documents;

/// <summary>
/// Builds the default Arabic contract wording — transcribed from the company's
/// reference supply-and-installation contract (10 numbered clauses: scope,
/// payment schedule, duration, warranty, cancellation, jurisdiction,
/// signatures), with the handful of fields that vary substituted in.
///
/// Staff type over this default in the contract editor — see
/// Boq.ContractText — so everything here is plain text, not a structured
/// model: once someone has edited it there is no further structure to trust
/// beyond the "البند" headings ContractPdfGenerator renders bold.
///
/// Two things the reference has that this company's own record does not yet
/// capture — the client's ID number and nationality — are left as bracketed
/// placeholders for staff to fill in, the same way a human would type them
/// into a blank contract.
/// </summary>
public sealed class ContractTextTemplate : IContractTextTemplate
{
    private const string CompanyBlock =
        "شركة/ جاما جو للمعدات الأمنية، رقم السجل التجاري/ 189177 ص ب/ 1920 الدوحة، قطر، " +
        "الهاتف/ 30644006، البريد الالكتروني/ gm@jamagoo.com - info@jamaelectronics.com";

    private const string CompanySignatory =
        "ويمثلها في التوقيع على هذا العقد السيد/ عبد الرحمن عبد العزيز محمد ، قطري الجنسية، " +
        "بطاقة رقم 29863405295، بصفته/ مدير مخولاً بالتوقيع عن الشركة.";

    public string BuildDefault(ContractTextModel model)
    {
        var date = ArabicLongDate(model.ContractDate);
        var client = string.IsNullOrWhiteSpace(model.ClientName) ? "[اسم العميل]" : model.ClientName;
        var site = string.IsNullOrWhiteSpace(model.SiteLocation) ? "[موقع المشروع]" : model.SiteLocation;
        var amount = model.GrandTotal.ToString("N2", CultureInfo.InvariantCulture);
        var wordsAr = MoneyWords.Arabic(model.GrandTotal);
        var (p1, p2, p3, p4) = PaymentSplit(model.GrandTotal);

        string Money(decimal value) => value.ToString("N2", CultureInfo.InvariantCulture);

        return $"""
            عقد توريد وتركيب
            "نظام كاميرات مراقبة أمنية كامل مرتبط بوزارة الداخلية"

            رقم العقد: {model.ContractNumber} — المراجعة: {model.RevisionNumber}

            حرر هذا العقد بتاريخ {date}، بين كل من:

            الطرف الأول: (المقاول/الشركة المنفذة):
            {CompanyBlock}

            {CompanySignatory}

            الطرف الثاني: (العميل/ المالك):
            {client}، [الجنسية]، بطاقة شخصية رقم: [رقم البطاقة الشخصية] بصفته مالك العقار محل العقد.

            تمهـــــيد:
            حيث أن الطرف الثاني يمتلك عقار ({site})، ويرغب في توريد وتركيب نظام كاميرات مراقبة أمنية وتجهيزه للحصول على كافة الموافقات الأمنية الرسمية والتراخيص المطلوبة من وزارة الداخلية، وبما أن الطرف الأول شركة متخصصة ومعتمدة ومُرخصة في هذا المجال وتتوفر لديها الخبرة الفنية والكادر المؤهل، وقد تقدمت للطرف الثاني بعرض السعر رقم ({model.ContractNumber}) بتاريخ {date}، وبناء عليه قد اتفق الطرفان وهما بأهليتهما المعتبرة قانوناً على الآتي:

            البند الأول: المرجعية والقوانين المنظمة
            يُعتبر التمهيد أعلاه وعرض السعر رقم ({model.ContractNumber}) وجدول الكميات (BOQ) المرفق والمخططات جزءاً لا يتجزأ من هذا العقد ومتمماً لأحكامه (في حال التعارض او الاختلاف بين عرض السعر وبنود العقد يتم تطبيق بنود العقد).
            يخضع هذا العقد ويتوافق مع أحكام القانون القطري بشأن تنظيم استخدام كاميرات وأجهزة المراقبة الأمنية واللوائح والقرارات التنفيذية الصادرة بموجبه، وكافة الاشتراطات الفنية المعتمدة من إدارة الأنظمة الأمنية بوزارة الداخلية القطرية (MOI - SSD).

            البند الثاني: نطاق ومجال العمل (Scope of Work)
            يلتزم الطرف الأول (المقاول/الشركة المنفذة) بتوريد، تركيب، تشغيل، وصيانة نظام كاميرات المراقبة الأمنية للطرف الثاني، شريطة أن يكون النظام مطابقاً كلياً للمواصفات الفنية والشروط المعتمدة لدى إدارة الأنظمة الأمنية بالإدارة العامة لنظم المعلومات بوزارة الداخلية القطرية، ومربوطاً بشكل مباشر بالنظام المركزي للإدارة الأمنية المختصة بالوزارة وفق الآليات والإجراءات القانونية والفنية المعمول بها والذي يشمل - دون حصر- الأعمال التالية:
            1. مرحلة التصميم (DSA): إعداد المخططات الهندسية ونظام التصاميم وتقديمها للبوابة الإلكترونية لإدارة النظم الأمنية بوزارة الداخلية للحصول على موافقة التصميم. (مدتها 2 أسابيع)
            2. الأعمال التأسيسية: توريد وتمديد أنابيب حماية الكابلات (Conduits)، سحب الكابلات المعتمدة، وتأسيس وتجهيز غرفة التحكم الأمنية. (مدتها 2 أسابيع)
            3. التوريد والتركيب: توريد وتثبيت الكاميرات، وحدات التسجيل (NVR)، لوحات التغذية الكهربائية، الملحقات، وإجراء كافة أعمال البرمجة والضبط التشغيلي. (مدتها 1 أسبوع)
            4. ربط نظام كاميرات كشف الوجه ونظام قارئ لوحات السيارات بإدارة النظم الأمنية. (مدتها 1 أسبوع)
            5. التفتيش والاستلام (DIA): إجراء الاختبارات التشغيلية والتجهيز للتفتيش النهائي واستخراج شهادة ترخيص النظام من وزارة الداخلية. (مدتها 2 أسابيع)

            البند الثالث: قيمة العقد وطريقة الدفع
            اتفق الطرفان على أن القيمة الإجمالية المقطوعة لأعمال التوريد والتركيب والاعتماد وكافة الأعمال موضوع هذا العقد موضحة كالتالي:
            القيمة الإجمالية {amount} ريال قطري ({wordsAr}). تسدد القيمة الإجمالية على أربع دفعات بموجب فواتير رسمية وفق الجدول التالي:
            - الدفعة الأولى 20% بمبلغ {Money(p1)} ريال قطري: دفعة مقدمة عند توقيع العقد.
            - الدفعة الثانية 20% بمبلغ {Money(p2)} ريال قطري: قبل توريد المعدات.
            - الدفعة الثالثة 40% بمبلغ {Money(p3)} ريال قطري: بعد التركيب وتشغيل النظام.
            - الدفعة الرابعة 20% بمبلغ {Money(p4)} ريال قطري: تستحق بعد التسليم النهائي، واستكمال الموافقات/الترخيص الأمني النهائي الذي يقع ضمن نطاق التزام الطرف الأول.

            البند الرابع: مدة تنفيذ الأعمال
            1- مدة التنفيذ وتاريخ البدء: تحددت مدة تنفيذ وتسليم جميع الأعمال موضوع هذا العقد بـ (60) يوماً تقويمياً، وتسري هذه المدة وتبدأ في الاحتساب تلقائياً اعتباراً من تاريخ توقيع العقد أو استلام الطرف الأول (المقاول) لقيمة الدفعة المقدمة في حسابه البنكي/أو استلام الشيك الصادر بها (يعتد بالتاريخ اللاحق).
            2- في حال تأخر الطرف الثاني عن سداد أي دفعة مستحقة في موعدها، يحق للطرف الأول إيقاف الأعمال مؤقتاً وتأجيل جدول التسليم لحين سداد الدفعة، ويتم إعادة تحديد مواعيد التسليم بإضافة مدة التأخير عن سداد الدفعة لمدة العقد، دون تحمل أي غرامات تأخير.

            البند الخامس: الضمان والصيانة (Warranty)
            1. ضمان الكاميرات وأجهزة التسجيل (NVR): يلتزم الطرف الأول بضمان الكاميرات وأجهزة التسجيل لمدة سنتين (2) تبدأ من تاريخ التسليم النهائي وحصول العقد على اعتماد وزارة الداخلية، واستخراج الطرف الأول لشهادة ترخيص النظام من وزارة الداخلية.
            2. ضمان باقي الأجهزة والمعدات: يضمن الطرف الأول كافة المعدات والمحولات الملحقة بالنظام لمدة سنتين (2) من تاريخ التسليم النهائي، واستخراج الطرف الأول لشهادة ترخيص النظام من وزارة الداخلية.
            3. يشمل الضمان عيوب التصنيع والتركيب، ولا يشمل الضمان الأعطال الناجمة عن الكوارث الطبيعية، أو سوء الاستخدام، أو العبث بالنظام من شخص غير مرخص.

            البند السادس: التغييرات والإضافات على العمل
            جميع أعمال تجهيزات غرفة التحكم من أعمال جبس / صبغ / تجهيزات أبواب / أعمال تكييف، يجب تجهيزها من الطرف الثاني.
            جميع أعمال الكهرباء اللازمة لتشغيل نظام كاميرات المراقبة من (غرفة التحكم) وملحقاتها IDF نقاط التوزيع الوسطية يجب تجهيزها من الطرف الثاني.
            لا يُعتد بأي اتفاق شفهي أو مراسلة غير رسمية عبر البريد الإلكتروني أو وسائل التواصل الاجتماعي ما لم تكن مكتوبة وموقعة بموجب ملحق للعقد موقع من الطرفين.

            البند السابع: إلغاء العقد
            في حال إلغاء العقد أو فسخه من طرف العميل لأي سبب كان قبل إتمام الأعمال، يلتزم الطرف الثاني بسداد القيمة المالية للأعمال والمعدات المنفذة والموردة بالفعل حتى تاريخ الإلغاء، ويتم تحديد وتقييم هذه القيمة بناءً على تقرير فني صادر من مهندس استشاري معتمد يتم اختياره من قبل الطرفين.

            البند الثامن: المسؤولية القانونية والتعويض
            يقر ويلتزم الطرف الثاني بالمسؤولية عن جميع العمال والمستخدمين التابعين له أو للمقاولين من الباطن الذين يستعين بهم لتنفيذ الأعمال أو الخدمات محل هذا العقد، ويكون وحده المسؤول مسؤولية قانونية، مدنية، وجنائية، وإدارية كاملة عن كافة تصرفاتهم وأعمالهم وإصاباتهم أو أي أضرار قد يلحقونها بالغير أو بـ (المالك) أو بالموقع أثناء تنفيذ العمل أو بسببه.
            كما يتعهد المقاول (الطرف الأول) بالالتزام الكامل بكافة قوانين ونظم العمل والتأمينات الاجتماعية والسلامة المعمول بها في الدولة، دون أي مسؤولية أو تبعة مالية أو قانونية على المالك (الطرف الثاني).

            البند التاسع: القانون الواجب التطبيق وحل النزاعات
            يخضع هذا العقد في تفسيره وتنفيذه للقوانين والأجهزة المعمول بها في دولة قطر. وفي حال نشوب أي نزاع حول تفسير أو تنفيذ هذا العقد، يكون الاختصاص للمحاكم القطرية على اختلاف درجاتها بالبت فيه.

            البند العاشر: نسخ العقد
            حُرر هذا العقد من نسختين أصليتين، وتسلم كل طرف نسخة للعمل بموجبها.
            """;
    }

    /// <summary>20% / 20% / 40% / 20%. The last share absorbs the rounding
    /// remainder so the four always sum to exactly the grand total, the same
    /// way a hand-typed payment table would be checked.</summary>
    private static (decimal, decimal, decimal, decimal) PaymentSplit(decimal total)
    {
        var p1 = Math.Round(total * 0.20m, 2);
        var p2 = Math.Round(total * 0.20m, 2);
        var p3 = Math.Round(total * 0.40m, 2);
        var p4 = total - p1 - p2 - p3;
        return (p1, p2, p3, p4);
    }

    private static readonly string[] ArabicMonths =
    [
        "يناير", "فبراير", "مارس", "أبريل", "مايو", "يونيو",
        "يوليو", "أغسطس", "سبتمبر", "أكتوبر", "نوفمبر", "ديسمبر",
    ];

    private static readonly string[] ArabicWeekdays =
    [
        "الأحد", "الإثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت",
    ];

    /// <summary>"يوم الثلاثاء الموافق 25 أكتوبر 2026م" — the form the reference
    /// contract opens with.</summary>
    private static string ArabicLongDate(DateTime value) =>
        $"يوم {ArabicWeekdays[(int)value.DayOfWeek]} الموافق {value.Day} {ArabicMonths[value.Month - 1]} {value.Year}م";
}
